import type { BusinessDataset, MonthlySale, SkuItem } from './types.ts';

type SeasonPattern = 'steady' | 'festive' | 'summer' | 'winter' | 'monsoon';
type StockPosture = 'critical' | 'reorder' | 'healthy' | 'overstock';

interface CatalogSeed {
  code: string;
  name: string;
  category: string;
  supplier: string;
  unitCost: number;
  unitPrice: number;
  baseMonthlyUnits: number;
  leadTimeDays: number;
  leadTimeStdDays: number;
  minOrderQty: number;
  season: SeasonPattern;
  posture: StockPosture;
  incoming?: number;
  serviceLevel?: number;
  holdingRate?: number;
  notes?: string;
}

